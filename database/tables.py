"""
creates the database schema
(patients, studies, series, instances, headers, logs, settings).
"""
import logging

from database.session import db_connection


def db_init(reset_tables: bool = False, logger: logging.Logger = None):
    """
    creates all pipeline tables (and drops them first if reset_tables=True).
    Runs in one transaction: if any statement fails, nothing is half-created.
    """
    if logger is None:
        logger = logging.getLogger(__name__)

    with db_connection() as conn, conn.cursor() as cur:
        _create_schema(cur, reset_tables, logger)

    logger.info("Database tables initialized (reset: %s)", reset_tables)


def _create_schema(cur, reset_tables: bool, logger: logging.Logger):
    """
    runs all the CREATE TABLE / INDEX statements
    """
    if reset_tables:
        logger.info("Resetting database tables...")
        cur.execute("DROP TABLE IF EXISTS customers CASCADE;")
        cur.execute("DROP TABLE IF EXISTS products CASCADE;")
        cur.execute("DROP TABLE IF EXISTS order_items CASCADE;")
        cur.execute("DROP TABLE IF EXISTS orders CASCADE;")

    cur.execute("""
        CREATE TABLE IF NOT EXISTS order_statuses (
            code         TEXT PRIMARY KEY,
            description  TEXT NOT NULL
        );

        INSERT INTO order_statuses (code, description) VALUES
            ('PENDING', 'Placed, awaiting payment'),
            ('PAID', 'Payment received'),
            ('SHIPPED', 'Sent to customer'),
            ('CANCELLED', 'Cancelled before shipping')
        ON CONFLICT (code) DO NOTHING;

    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS product_statuses (
            code         TEXT PRIMARY KEY,
            description  TEXT NOT NULL
        );

        INSERT INTO product_statuses (code, description) VALUES
            ('ACTIVE', 'Available for sale'),
            ('DISCONTINUED', 'No longer sold')
        ON CONFLICT (code) DO NOTHING;

    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS customers (
            customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email       TEXT NOT NULL UNIQUE,
            first_name  TEXT NOT NULL CHECK (length(first_name) > 0),
            last_name   TEXT NOT NULL CHECK (length(last_name) > 0),
            country     CHAR(2) NOT NULL CHECK (country ~ '^[A-Z]{2}$'),
            active      BOOLEAN NOT NULL DEFAULT TRUE,
            created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE INDEX IF NOT EXISTS idx_customers_updated_at ON customers (updated_at);

    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS products (
            product_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sku         TEXT NOT NULL UNIQUE CHECK (sku ~ '^[A-Z]{3}-[0-9]{4}$'),
            name        TEXT NOT NULL CHECK (length(name) > 0),
            category    TEXT NOT NULL CHECK (length(category) > 0),
            price       NUMERIC(10, 2) NOT NULL CHECK (price > 0),
            currency    CHAR(3) NOT NULL CHECK (currency IN ('EUR', 'USD', 'GBP')),
            stock       INTEGER NOT NULL CHECK (stock >= 0),
            status      TEXT NOT NULL DEFAULT 'ACTIVE' REFERENCES product_statuses (code),
            created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE INDEX IF NOT EXISTS idx_products_updated_at ON products (updated_at);

    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS orders (
            order_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_id  INTEGER NOT NULL REFERENCES customers (customer_id),
            currency     CHAR(3) NOT NULL CHECK (currency IN ('EUR', 'USD', 'GBP')),
            status      TEXT NOT NULL DEFAULT 'PENDING' REFERENCES order_statuses (code),
            created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
        );

        CREATE INDEX IF NOT EXISTS idx_orders_customer_id ON orders (customer_id);
        CREATE INDEX IF NOT EXISTS idx_orders_updated_at ON orders (updated_at);

    """)

    cur.execute("""
        CREATE TABLE IF NOT EXISTS order_items (
            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            order_id    INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
            product_id  INTEGER NOT NULL REFERENCES products (product_id),
            sku         TEXT NOT NULL,
            unit_price  NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0),
            currency    CHAR(3) NOT NULL CHECK (currency IN ('EUR', 'USD', 'GBP')),
            quantity    INTEGER NOT NULL CHECK (quantity > 0)
        );

        CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items (order_id);
        CREATE INDEX IF NOT EXISTS idx_order_items_product_id ON order_items (product_id);

    """)